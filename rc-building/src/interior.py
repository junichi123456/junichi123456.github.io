def stair_checks(h):
    st = h.spec["interior"]["stair"]
    out = []
    for s in h.stairs:
        r, t = s.riser, s.tread
        out.append(dict(name=s.name, riser=r, tread=t, slope=r / t, rule=2 * r + t, width=s.width,
                        ok_slope=r / t <= st["max_slope"], ok_rule=st["step_rule"][0] <= 2 * r + t <= st["step_rule"][1]))
    return out


def guard_gaps(h):
    """手すり壁・腰壁の端と隣の壁とのすき間（mm）。0 ならすき間なし。"""
    z = h.fl["2F"] + 500
    solids = [b for b in h.boxes if b.cat in ("wall", "partition") and b.z0 < z < b.z1]
    res = []
    for name, g in h.guards:
        gp = sbox(g.x0, g.y0, g.x1, g.y1)
        others = [sbox(b.x0, b.y0, b.x1, b.y1) for b in solids if b is not g]
        long_x = (g.x1 - g.x0) >= (g.y1 - g.y0)
        ends = ([sbox(g.x0, g.y0, g.x0 + 1, g.y1), sbox(g.x1 - 1, g.y0, g.x1, g.y1)] if long_x
                else [sbox(g.x0, g.y0, g.x1, g.y0 + 1), sbox(g.x0, g.y1 - 1, g.x1, g.y1)])
        gaps = [min(e.distance(o) for o in others) for e in ends]
        res.append(dict(stair=name, length=max(g.x1 - g.x0, g.y1 - g.y0), height=g.z1 - h.fl["2F"], gaps=gaps))
    return res
