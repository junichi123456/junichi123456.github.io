def finish_of(name):
    for key, f in FINISH_RULES:
        if key in name:
            return f
    return FINISH_RULES[-1][1]


def finish_schedule(h):
    """室名・階でまとめた内装仕上表。"""
    rows = {}
    for r in h.rooms:
        k = (r.floor, r.name)
        rows.setdefault(k, [0, 0.0])
        rows[k][0] += 1
        rows[k][1] += r.area
    return [(f, n, c, a, finish_of(n)) for (f, n), (c, a) in rows.items()]


